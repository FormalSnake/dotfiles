-- Colours are the terminal's own 16 ANSI slots, never hex. termguicolors stays
-- off so the outermost terminal resolves every index against its palette:
-- matugen on the g815 Ghostty, Flexoki on the mac, and that survives SSH,
-- mosh, tmux and herdr in between, where an OSC palette query or a truecolor
-- value would not. Backgrounds stay NONE for transparency; selections use
-- reverse video because slot 0 equals the background in both palettes.
vim.cmd.highlight("clear")
vim.g.colors_name = "terminal"

local black, red, green, yellow, blue, magenta, cyan = 0, 1, 2, 3, 4, 5, 6
local dim, faint = 7, 8 -- secondary text, borders and gutters

local function hl(group, spec)
  if type(spec) == "string" then
    vim.api.nvim_set_hl(0, group, { link = spec })
    return
  end
  local attrs = {}
  for _, a in ipairs(spec) do
    attrs[a] = true
  end
  vim.api.nvim_set_hl(0, group, {
    ctermfg = spec.fg,
    ctermbg = spec.bg,
    cterm = attrs,
  })
end

